import { UNTRUSTED_DATA_RULE } from '../security/injection';
import type { AgentRole } from './agents';

export function buildAgentPrompt(role: AgentRole, projectPath: string): string {
  return [
    `Ты — субагент «${role.title}» ассистента Джарвис. Отвечай по-русски, технически точно и кратко.`,
    role.mission,
    projectPath ? `Рабочий проект: ${projectPath}` : '',
    'Работай только через предоставленные инструменты и только в разрешённых папках. Если инструмент отказал или пользователь отклонил действие — не пытайся обойти это, сообщи в отчёте.',
    'Не заявляй, что что-то сделано или проверено, если инструмент не вернул успех. Приводи реальные результаты запусков (кол-во тестов, коды выхода).',
    'Закончи работу итоговым отчётом: что сделано, какие файлы изменены, результаты проверок, что осталось сделать.',
    UNTRUSTED_DATA_RULE,
  ]
    .filter(Boolean)
    .join('\n\n');
}
