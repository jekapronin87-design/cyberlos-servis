export type Step =
  | { kind: 'explain'; text: string; kb?: string }
  | { kind: 'quiz'; question: string; options: string[]; correct: number; explain: string }
  | {
      kind: 'task';
      text: string;
      /** self — сотрудник подтверждает сам; crm_training_deal — проверка по тестовой CRM (только тестовое окружение). */
      verify: 'self' | 'crm_training_deal';
      /** Что подсветить в CRM, когда нажата «Показать в CRM». */
      show?: { path?: string; text?: string; selector?: string; hint: string };
    };

export interface Lesson {
  id: string;
  title: string;
  goal: string;
  steps: Step[];
}

export interface Course {
  id: string;
  title: string;
  description: string;
  /** Ключи ролей CRM, для которых курс рекомендован ('*' — всем). */
  roles: string[];
  lessons: Lesson[];
}

